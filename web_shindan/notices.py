def self_sha256():
    """exe 自身の SHA-256。開発中(python で動かしている時)は None。"""
    if not getattr(sys, "frozen", False):
        return None
    h = hashlib.sha256()
    with open(sys.executable, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest().upper()


